import React, { useState } from 'react';
import { 
  AreaChart, 
  Area, 
  XAxis, 
  YAxis, 
  CartesianGrid, 
  Tooltip, 
  ResponsiveContainer 
} from 'recharts';
import { useAirQuality } from '../../context/AirQualityContext';
import { 
  Calendar, 
  Info, 
  CheckCircle2, 
  AlertCircle,
  Sparkles,
  Wind,
  ShieldCheck
} from 'lucide-react';
import { predictAqiTrajectory } from '../../services/mlPredictionService';
import { formatDateShort, formatTime } from '../../utils/formatters';

export const ForecastView: React.FC = () => {
  const { hourlyForecast, hourlyHistory, weatherData, isLoading } = useAirQuality();
  const [forecastHorizon, setForecastHorizon] = useState<'24h' | '48h' | '72h' | '5d'>('48h');

  if (isLoading || hourlyForecast.length === 0) {
    return (
      <div className="bg-white border border-[#E3E6DC] rounded-3xl p-8 animate-pulse text-center shadow-card">
        <div className="h-5 w-48 bg-[#EEF1E8] rounded-full mx-auto mb-4" />
        <div className="h-64 bg-[#EEF1E8] rounded-2xl" />
      </div>
    );
  }

  const limitHours = forecastHorizon === '24h' ? 24 : forecastHorizon === '48h' ? 48 : forecastHorizon === '72h' ? 72 : 120;
  const filteredForecast = hourlyForecast.slice(0, limitHours);

  const mlPredictions = predictAqiTrajectory(
    hourlyHistory, 
    weatherData?.windSpeed || 8, 
    weatherData?.humidity || 60
  );

  let bestWindow = filteredForecast[0];
  let peakSmog = filteredForecast[0];
  for (const item of filteredForecast) {
    if (item.aqi < bestWindow.aqi) bestWindow = item;
    if (item.aqi > peakSmog.aqi) peakSmog = item;
  }

  return (
    <div className="space-y-6">
      
      {/* Explicit Distinction Note */}
      <div className="p-4 rounded-2xl bg-white border border-[#E3E6DC] shadow-soft flex items-start gap-3.5 text-xs">
        <ShieldCheck className="w-5 h-5 text-[#2D6A4F] flex-shrink-0 mt-0.5" />
        <p className="text-[#58645C] leading-relaxed">
          <strong className="text-[#173D32] font-heading font-semibold">Authentic Scientific Forecast: </strong>
          This 5-day hourly trajectory is generated by the Copernicus Atmosphere Monitoring Service (CAMS) integrated with NOAA GFS atmospheric transport models. 
          Values reflect regional particulate dispersal and chemical formation, and are clearly distinguished from live ground station telemetry.
        </p>
      </div>

      {/* Main Forecast Chart Card */}
      <div className="bg-white border border-[#E3E6DC] rounded-3xl p-6 sm:p-8 shadow-card">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 mb-6">
          <div>
            <h2 className="text-base font-bold font-heading text-[#173D32] tracking-tight flex items-center gap-2">
              <Calendar className="w-4 h-4 text-[#8B5E3C]" />
              <span>Projected Air Quality Trajectory</span>
            </h2>
            <p className="text-xs text-[#58645C] mt-0.5">
              Hourly dispersion projection mapping diurnal smog accumulation, daylight solar updrafts, and night boundary trapping
            </p>
          </div>

          <div className="flex items-center rounded-xl bg-[#EEF1E8] p-1 border border-[#E3E6DC]">
            {(['24h', '48h', '72h', '5d'] as const).map(horizon => (
              <button
                key={horizon}
                onClick={() => setForecastHorizon(horizon)}
                className={`px-3 py-1 text-xs font-semibold font-heading rounded-lg transition-all ${
                  forecastHorizon === horizon
                    ? 'bg-[#173D32] text-[#F7F5ED] shadow-soft'
                    : 'text-[#58645C] hover:text-[#173D32]'
                }`}
              >
                {horizon.toUpperCase()}
              </button>
            ))}
          </div>
        </div>

        {/* Forecast Recharts Area */}
        <div className="w-full h-72">
          <ResponsiveContainer width="100%" height="100%">
            <AreaChart data={filteredForecast}>
              <defs>
                <linearGradient id="forecastCleanGrad" x1="0" y1="0" x2="0" y2="1">
                  <stop offset="5%" stopColor="#65B9C9" stopOpacity={0.35} />
                  <stop offset="95%" stopColor="#65B9C9" stopOpacity={0.0} />
                </linearGradient>
              </defs>
              <CartesianGrid strokeDasharray="3 3" stroke="#EEF1E8" />
              <XAxis dataKey="formattedTime" stroke="#89938A" fontSize={11} tickMargin={6} />
              <YAxis dataKey="aqi" stroke="#89938A" fontSize={11} domain={[0, 'dataMax + 25']} tickMargin={6} />
              <Tooltip
                content={({ active, payload }) => {
                  if (active && payload && payload.length) {
                    const d = payload[0].payload;
                    return (
                      <div className="bg-white border border-[#E3E6DC] p-3 rounded-2xl shadow-card text-xs">
                        <span className="text-[10px] uppercase font-bold text-[#173D32] font-heading block mb-0.5">
                          Atmospheric Trajectory
                        </span>
                        <p className="font-semibold text-[#26332D]">{formatDateShort(d.time)} {d.formattedTime}</p>
                        <p className="font-bold text-[#173D32] text-base mt-1 font-mono font-heading">Expected AQI {d.aqi}</p>
                        <p className="text-[#58645C] font-mono text-[11px]">Est. PM2.5: {d.pm2_5} µg/m³</p>
                      </div>
                    );
                  }
                  return null;
                }}
              />
              <Area
                type="monotone"
                dataKey="aqi"
                stroke="#65B9C9"
                strokeWidth={2.5}
                strokeDasharray="4 4"
                fillOpacity={1}
                fill="url(#forecastCleanGrad)"
                name="Projected AQI"
              />
            </AreaChart>
          </ResponsiveContainer>
        </div>
      </div>

      {/* Actionable Windows: Best vs Peak Hours */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        
        {/* Optimal Window */}
        <div className="p-5 rounded-2xl bg-white border border-[#E3E6DC] shadow-soft flex items-start gap-4">
          <div className="p-2.5 rounded-xl bg-[#EEF1E8] text-[#2D6A4F] flex-shrink-0 mt-0.5">
            <CheckCircle2 className="w-5 h-5" />
          </div>
          <div>
            <span className="text-[10px] font-bold uppercase tracking-wider text-[#2D6A4F] font-heading block">
              Optimal Outdoor Window
            </span>
            <h4 className="text-sm font-bold font-heading text-[#173D32] mt-0.5">
              {formatDateShort(bestWindow.time)} at {bestWindow.formattedTime}
            </h4>
            <p className="text-xs text-[#58645C] mt-1.5 leading-relaxed">
              Lowest expected pollution: <strong className="text-[#173D32] font-mono">{bestWindow.aqi} AQI</strong> (PM2.5: {bestWindow.pm2_5} µg/m³). 
              Solar thermal updrafts maximize boundary mixing. Ideal timing for workouts and errands.
            </p>
          </div>
        </div>

        {/* Peak Smog Window */}
        <div className="p-5 rounded-2xl bg-white border border-[#E3E6DC] shadow-soft flex items-start gap-4">
          <div className="p-2.5 rounded-xl bg-[#A83232]/10 text-[#A83232] flex-shrink-0 mt-0.5">
            <AlertCircle className="w-5 h-5" />
          </div>
          <div>
            <span className="text-[10px] font-bold uppercase tracking-wider text-[#A83232] font-heading block">
              Projected Smog Peak
            </span>
            <h4 className="text-sm font-bold font-heading text-[#173D32] mt-0.5">
              {formatDateShort(peakSmog.time)} at {peakSmog.formattedTime}
            </h4>
            <p className="text-xs text-[#58645C] mt-1.5 leading-relaxed">
              Highest anticipated spike: <strong className="text-[#A83232] font-mono">{peakSmog.aqi} AQI</strong> (PM2.5: {peakSmog.pm2_5} µg/m³). 
              Driven by night thermal trapping. Keep windows closed and operate indoor HEPA purifiers.
            </p>
          </div>
        </div>

      </div>

      {/* 12-Hour ML Statistical Prediction */}
      {mlPredictions.length > 0 && (
        <div className="bg-white border border-[#E3E6DC] rounded-3xl p-6 sm:p-8 shadow-card">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 mb-5">
            <div>
              <h3 className="text-sm font-bold font-heading text-[#173D32] flex items-center gap-2">
                <Sparkles className="w-4 h-4 text-[#65B9C9]" />
                <span>Next 12-Hour Auto-Regressive ML Trajectory</span>
              </h3>
              <p className="text-xs text-[#58645C] mt-0.5">
                Exponential smoothing weighted by boundary layer wind and humidity vectors
              </p>
            </div>
            <span className="text-[10px] px-2.5 py-0.5 rounded-full bg-[#EEF1E8] text-[#173D32] font-mono border border-[#E3E6DC] self-start sm:self-auto">
              Auto-Regressive ML
            </span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-3 md:grid-cols-6 gap-3">
            {mlPredictions.slice(0, 6).map((pred) => (
              <div
                key={pred.hourOffset}
                className="p-3.5 rounded-2xl bg-[#EEF1E8]/50 border border-[#E3E6DC] text-center"
              >
                <span className="text-[11px] font-semibold text-[#58645C] block">
                  +{pred.hourOffset}h ({formatTime(pred.time)})
                </span>
                <span className="text-2xl font-bold font-mono text-[#173D32] my-1 block">
                  {pred.predictedAqi}
                </span>
                <span className="text-[10px] text-[#89938A] font-mono block">
                  Range: {pred.lowerConfidence}-{pred.upperConfidence}
                </span>
                <span className="mt-2 inline-block text-[9px] font-medium px-2 py-0.5 rounded-full bg-white text-[#2D6A4F] border border-[#E3E6DC]">
                  {pred.confidencePercent}% conf.
                </span>
              </div>
            ))}
          </div>
        </div>
      )}

    </div>
  );
};
